from __future__ import annotations

import json
import os
import shutil
import sys
from datetime import datetime
from pathlib import Path

# Runtime paths are configurable, rather than tied to one Windows username or drive.
_DEFAULT_DATA_HOME = Path(os.environ.get("LOCALAPPDATA") or Path.home())
DATA_ROOT = Path(os.environ.get("BILIWATCH_DATA") or (_DEFAULT_DATA_HOME / "bilibili-watch")).expanduser()
AUTH_DIR = DATA_ROOT / "auth"
AUTH_JSON = AUTH_DIR / "cookies.json"
YUTTO_AUTH = AUTH_DIR / "yutto-auth.toml"
CHROME_PROFILE = DATA_ROOT / "chrome-profile"
RUNS_DIR = DATA_ROOT / "runs"
MODELS_DIR = DATA_ROOT / "models"

VENV_PYTHON = Path(os.environ.get("BILIWATCH_PYTHON") or sys.executable).expanduser()


def _yutto_exe() -> Path:
    configured = os.environ.get("BILIWATCH_YUTTO")
    if configured:
        return Path(configured).expanduser()
    sibling = VENV_PYTHON.parent / ("yutto.exe" if os.name == "nt" else "yutto")
    if sibling.is_file():
        return sibling
    found = shutil.which("yutto")
    return Path(found) if found else sibling


YUTTO_EXE = _yutto_exe()
FFMPEG_FALLBACKS: tuple[str, ...] = ()
FFPROBE_FALLBACKS: tuple[str, ...] = ()


def ensure_dirs() -> None:
    for path in (AUTH_DIR, RUNS_DIR, MODELS_DIR):
        path.mkdir(parents=True, exist_ok=True)


def load_auth_doc() -> dict:
    if not AUTH_JSON.exists():
        return {}
    try:
        return json.loads(AUTH_JSON.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}


def load_cookies() -> dict[str, str]:
    cookies = load_auth_doc().get("cookies") or {}
    return {str(k): str(v) for k, v in cookies.items() if v}


def save_auth(cookies: dict[str, str], mid: int | str | None = None, uname: str | None = None) -> None:
    ensure_dirs()
    doc = {
        "saved_at": datetime.now().astimezone().isoformat(timespec="seconds"),
        "mid": str(mid) if mid is not None else None,
        "uname": uname,
        "cookies": dict(cookies),
    }
    AUTH_JSON.write_text(json.dumps(doc, ensure_ascii=False, indent=2), encoding="utf-8")

    lines = [
        "# Generated by bilibili-watch; keep private.",
        "",
        "[profiles.default]",
        f"sessdata = {json.dumps(cookies.get('SESSDATA', ''), ensure_ascii=False)}",
    ]
    if cookies.get("bili_jct"):
        lines.append(f"bili_jct = {json.dumps(cookies['bili_jct'], ensure_ascii=False)}")
    lines.append(f"updated_at = {json.dumps(doc['saved_at'])}")
    YUTTO_AUTH.write_text("\n".join(lines) + "\n", encoding="utf-8")


def clear_auth() -> list[str]:
    removed = []
    for path in (AUTH_JSON, YUTTO_AUTH):
        if path.exists():
            path.unlink()
            removed.append(str(path))
    return removed


def find_executable(name: str, fallbacks: tuple[str, ...] = ()) -> str:
    env_key = f"BILIWATCH_{name.upper()}"
    if os.environ.get(env_key):
        configured = os.environ[env_key]
        if Path(configured).is_file():
            return configured
        return shutil.which(configured) or ""
    for candidate in fallbacks:
        if Path(candidate).exists():
            return candidate
    found = shutil.which(name)
    if found:
        return found
    return ""


def ffmpeg_bin() -> str:
    return find_executable("ffmpeg", FFMPEG_FALLBACKS)


def ffprobe_bin() -> str:
    return find_executable("ffprobe", FFPROBE_FALLBACKS)


def format_duration(seconds: float | int | None) -> str:
    total = int(seconds or 0)
    hours, rem = divmod(total, 3600)
    minutes, secs = divmod(rem, 60)
    if hours:
        return f"{hours:02d}:{minutes:02d}:{secs:02d}"
    return f"{minutes:02d}:{secs:02d}"


def format_time(timestamp: int | float | None) -> str:
    if not timestamp:
        return ""
    return datetime.fromtimestamp(int(timestamp)).strftime("%Y-%m-%d %H:%M")